# variable = A container for a value(string, number, boolean, etc.) A variable behaves as the name for that value.
first_name = "Nitin"
food = "Pizza"
email = "nitin@email.com"
# these are string variables
print(f"Hello {first_name}")
print(f"You like {food}")   
print(f"Your email is: {email}")

